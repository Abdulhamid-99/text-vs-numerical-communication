"""Aggregate all sweep_*/episodes.csv files into one summary CSV + summary stats.

Usage:
    python scripts/aggregate_sweep.py
Output:
    data/results/sweep_summary.csv  (one row per cell)
    data/results/sweep_summary.md   (markdown table for the supervisor report)
"""
from __future__ import annotations

import csv
import glob
import os
from pathlib import Path

ROOT = Path(__file__).parent.parent
RESULTS = ROOT / "data" / "results"


def parse_cell_name(cell: str) -> dict:
    """cell = 'llama_text_high_clean' -> {model, channel, budget, network}"""
    parts = cell.split("_")
    if len(parts) < 4:
        return {"model": parts[0] if parts else "?", "channel": "?", "budget": "?", "network": "?"}
    return {
        "model": parts[0],
        "channel": parts[1],
        "budget": parts[2],
        "network": parts[3] if len(parts) > 3 else "clean",
    }


def main() -> None:
    rows = []
    for d in sorted(RESULTS.glob("sweep_*")):
        p = d / "episodes.csv"
        if not p.exists():
            continue
        with p.open(encoding="utf-8") as f:
            episodes = list(csv.DictReader(f))
        if not episodes:
            continue

        cell = d.name.replace("sweep_", "")
        labels = parse_cell_name(cell)
        n = len(episodes)
        succ = sum(1 for r in episodes if r["success"] == "True")
        bits = [int(r["bits_used"]) for r in episodes]
        ms = [float(r["wall_time_ms"]) for r in episodes]
        blk = sum(int(r.get("n_blocked", 0)) for r in episodes)
        drp = sum(int(r.get("n_dropped", 0)) for r in episodes)

        rows.append(
            {
                "cell": cell,
                **labels,
                "n_episodes": n,
                "em_correct": succ,
                "em_accuracy": round(100 * succ / n, 2),
                "mean_bits_per_ep": round(sum(bits) / n, 1),
                "mean_wall_ms": round(sum(ms) / n, 1),
                "total_blocked": blk,
                "total_dropped": drp,
                "blocked_pct": round(100 * blk / (n * 8), 1),  # 8 msgs/ep
                "dropped_pct": round(100 * drp / (n * 8), 1),
            }
        )

    # Sort: by model, channel, budget, network
    sort_keys = {"clean": 0, "loss5": 1, "loss10": 2}
    budget_keys = {"high": 0, "low": 1}
    channel_keys = {"text": 0, "vector": 1, "hybrid": 2}
    rows.sort(
        key=lambda r: (
            r["model"],
            channel_keys.get(r["channel"], 9),
            budget_keys.get(r["budget"], 9),
            sort_keys.get(r["network"], 9),
        )
    )

    out_csv = RESULTS / "sweep_summary.csv"
    with out_csv.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    # Markdown
    out_md = RESULTS / "sweep_summary.md"
    with out_md.open("w", encoding="utf-8") as f:
        f.write("# Sweep summary\n\n")
        f.write(f"{len(rows)} cells aggregated\n\n")
        f.write(
            "| cell | model | ch | budget | net | n | EM% | bits | ms | blk% | drp% |\n"
        )
        f.write("|---|---|---|---|---|---|---|---|---|---|---|\n")
        for r in rows:
            f.write(
                f"| {r['cell']} | {r['model']} | {r['channel']} | {r['budget']} | "
                f"{r['network']} | {r['n_episodes']} | {r['em_accuracy']:.1f} | "
                f"{r['mean_bits_per_ep']:.0f} | {r['mean_wall_ms']:.0f} | "
                f"{r['blocked_pct']:.1f} | {r['dropped_pct']:.1f} |\n"
            )
        f.write(f"\n_Generated by `scripts/aggregate_sweep.py`._\n")

    print(f"Wrote {out_csv}")
    print(f"Wrote {out_md}")
    print(f"Cell count: {len(rows)}")


if __name__ == "__main__":
    main()
